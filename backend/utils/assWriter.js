/**
 * Renders one phrase as flat, single-color text with no per-word active/
 * inactive/keyword coloring or animation — the Unified Shadow is one static
 * silhouette of the whole phrase for its entire on-screen duration, not a
 * per-word-timed highlight like the real caption track.
 */
function buildFlatPhraseText(phrase, textCase, enableKeywordHighlighting, keywordTextCase) {
  const breakIndices = new Set(phrase.breakAfterIndices || []);
  return phrase.words.map((w, idx) => {
    const raw = (w.word || w.text || '').trim();
    const caseForWord = resolveWordTextCase(!!w.isKeyword, enableKeywordHighlighting, textCase, keywordTextCase);
    const wordText = applyCaseTransform(raw, caseForWord, idx === 0);
    const isLineBreak = breakIndices.has(idx - 1);
    const isFirstWord = idx === 0;
    const prefixSpace = (isFirstWord || isLineBreak) ? '' : ' ';
    const lineBreakTag = isLineBreak ? '\\N' : '';
    return `${lineBreakTag}${prefixSpace}${wordText}`;
  }).join('');
}

/**
 * Builds one Unified Shadow Dialogue event for a phrase — visible for the
 * phrase's entire on-screen duration, positioned identically to the real
 * caption (same posOverrideTag), matching the CSS preview's single flat
 * `filter: drop-shadow(...)` silhouette.
 *
 * @param {object} phrase - Unified phrase (start, end, words, breakAfterIndices).
 * @param {object} options - { textCase, posOverrideTag, enableKeywordHighlighting, keywordTextCase }.
 */
export function generateUnifiedShadowDialogueLine(phrase, options = {}) {
  const textCase = options.textCase || 'uppercase';
  const posOverrideTag = options.posOverrideTag || '';
  const text = buildFlatPhraseText(phrase, textCase, options.enableKeywordHighlighting, options.keywordTextCase || null);
  return `Dialogue: 0,${formatASSTimestamp(phrase.start)},${formatASSTimestamp(phrase.end)},Shadow,,0,0,0,,${posOverrideTag}${text}`;
}

/**
 * Word Mode's Unified Shadow events: one silhouette event per WORD, timed to
 * that word's own start/end — matching Word Mode's real caption track (only
 * one word is ever on screen, so the "whole caption" the unified shadow
 * silhouettes is just that one word for as long as it in turn is visible),
 * instead of one event per whole phrase.
 *
 * @param {object} phrase - Unified phrase (words array with per-word start/end).
 * @param {object} options - { textCase, posOverrideTag, enableKeywordHighlighting, keywordTextCase }.
 * @returns {string} Newline-joined ASS Dialogue Event lines, one per word.
 */
export function generateUnifiedShadowWordDialogueEvents(phrase, options = {}) {
  const textCase = options.textCase || 'uppercase';
  const posOverrideTag = options.posOverrideTag || '';

  return phrase.words
    .filter((w) => w.end - w.start >= 0.001)
    .map((w) => {
      const caseForWord = resolveWordTextCase(!!w.isKeyword, options.enableKeywordHighlighting, textCase, options.keywordTextCase || null);
      const wordText = applyCaseTransform((w.word || w.text || '').trim(), caseForWord, true);
      return `Dialogue: 0,${formatASSTimestamp(w.start)},${formatASSTimestamp(w.end)},Shadow,,0,0,0,,${posOverrideTag}${wordText}`;
    })
    .join('\n');
}

/**
 * Rolling Stack's Unified Shadow events: one flat, two-line silhouette event
 * per rolling-stack slice (see generateRollingStackDialogueEvents), reusing
 * the exact same shared slicing so the shadow layer's shape and timing always
 * matches the real caption track — same top/bottom line pairing, just flat
 * single-color text with no per-chunk keyword styling.
 *
 * @param {object} phrase - Unified phrase (start, end, words[]).
 * @param {object} options - { textCase, posOverrideTag, enableKeywordHighlighting, keywordTextCase }.
 * @returns {string} Newline-joined ASS Dialogue Event lines, one per slice.
 */
export function generateUnifiedShadowRollingStackDialogueEvents(phrase, options = {}) {
  const textCase = options.textCase || 'uppercase';
  const posOverrideTag = options.posOverrideTag || '';
  const slices = buildRollingStackSlices(phrase);

  return slices.map((slice) => {
    const bottomCase = resolveWordTextCase(slice.bottom.type === 'keyword', options.enableKeywordHighlighting, textCase, options.keywordTextCase || null);
    const bottomText = applyCaseTransform(chunkRawText(slice.bottom), bottomCase, true);
    let text = bottomText;
    if (slice.top) {
      const topCase = resolveWordTextCase(slice.top.type === 'keyword', options.enableKeywordHighlighting, textCase, options.keywordTextCase || null);
      text = `${applyCaseTransform(chunkRawText(slice.top), topCase, true)}\\N${bottomText}`;
    }
    return `Dialogue: 0,${formatASSTimestamp(slice.start)},${formatASSTimestamp(slice.end)},Shadow,,0,0,0,,${posOverrideTag}${text}`;
  }).join('\n');
}

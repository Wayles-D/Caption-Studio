import { buildRollingStackSlices, chunkRawText } from '../../shared/rollingStack.js';

/**
 * Formats a duration in seconds to the standard ASS timestamp format: H:MM:SS.cs
 * e.g., 0:02:14.35 (where cs is centiseconds, 1cs = 10ms)
 *
 * @param {number} seconds - The time in seconds.
 * @returns {string} The formatted timestamp.
 */
export function formatASSTimestamp(seconds) {
  if (typeof seconds !== 'number' || isNaN(seconds) || seconds < 0) {
    seconds = 0;
  }
  const hrs = Math.floor(seconds / 3600);
  const mins = Math.floor((seconds % 3600) / 60);
  const secs = Math.floor(seconds % 60);

  // Calculate centiseconds (.00 to .99)
  const cs = Math.round((seconds - Math.floor(seconds)) * 100);

  const formattedHrs = hrs.toString();
  const formattedMins = mins.toString().padStart(2, '0');
  const formattedSecs = secs.toString().padStart(2, '0');
  const formattedCs = Math.min(99, Math.max(0, cs)).toString().padStart(2, '0');

  return `${formattedHrs}:${formattedMins}:${formattedSecs}.${formattedCs}`;
}

/**
 * Builds the ASS format string header with metadata and styles configured for short form video.
 *
 * @param {object} styles - The resolved style preferences.
 * @returns {string} The formatted file header sections.
 */
export function generateASSHeader(styles = {}) {
  const fontName = styles.fontName || 'Montserrat SemiBold';
  const fontSize = styles.fontSize || 72;
  const primaryColor = styles.primaryColor || '&H0000FFFF';
  const secondaryColor = styles.secondaryColor || '&H00FFFFFF';
  const outlineColor = styles.outlineColor || '&H00000000';
  const backColor = styles.backColor || '&H00000000';
  const bold = styles.bold !== undefined ? styles.bold : -1;
  const outlineSize = styles.outlineSize !== undefined ? styles.outlineSize : 5;
  const shadowSize = styles.shadowSize !== undefined ? styles.shadowSize : 0;
  const alignment = styles.alignment || 2;
  const marginV = styles.marginV !== undefined ? styles.marginV : 300;
  const borderStyle = styles.borderStyle !== undefined ? styles.borderStyle : 1;
  const spacing = styles.spacing !== undefined ? styles.spacing : 0;

  return [
    '[Script Info]',
    '; Script generated by Caption Studio',
    'Title: Caption Studio Subtitles',
    'ScriptType: v4.00+',
    'WrapStyle: 0',
    'PlayResX: 1080',
    'PlayResY: 1920', // Configured for vertical 9:16 environments
    'ScaledBorderAndShadow: yes',
    '',
    '[V4+ Styles]',
    'Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding',
    `Style: Default,${fontName},${fontSize},${primaryColor},${secondaryColor},${outlineColor},${backColor},${bold},0,0,0,100,100,${spacing},0,${borderStyle},${outlineSize},${shadowSize},${alignment},100,100,${marginV},1`,
    '',
    '[Events]',
    'Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text'
  ].join('\n');
}

// Fallback colors used only when a caller (e.g. direct unit tests) omits the
// resolved style colors — production calls always pass the real resolved values.
const DEFAULT_PRIMARY_COLOR = '&H0000FFFF';
const DEFAULT_SECONDARY_COLOR = '&H00FFFFFF';

/**
 * Converts an 8-hex AABBGGRR ASS color string (as used in [V4+ Styles]) into
 * inline override tags (\Na\Nc) that force that exact color for a text run,
 * regardless of the Dialogue event's Style-level default color.
 *
 * @param {string} assColor - Color string such as '&H0000FFFF'.
 * @param {number} index - Color slot to target (1 = Primary/fill).
 * @returns {string} Inline alpha + color override tags.
 */
function toInlineColorTags(assColor, index) {
  const clean = (assColor || DEFAULT_PRIMARY_COLOR).replace(/^&H/i, '').replace(/&$/, '').padStart(8, '0');
  const alpha = clean.substring(0, 2);
  const bgr = clean.substring(2, 8);
  return `\\${index}a&H${alpha}&\\${index}c&H${bgr}&`;
}

/**
 * Builds the one-time inline override block (placed at the very start of a
 * Dialogue event's text) that sets the shadow color, the shadow's X/Y offset
 * (if explicitly customized), and — for the Individual shadow — a Gaussian
 * edge blur. ASS has no dedicated shadow-color style column — shadow color is
 * the \4a\4c override tags, which is why this has to be inline rather than
 * baked into [V4+ Styles] like Outline/Shadow depth are. Override tags
 * persist for the rest of that Dialogue event's text once set, so this only
 * needs to be emitted once per event, not per word.
 *
 * Blur: libass's native \blur tag Gaussian-blurs glyph EDGES only — the
 * border/outline and the shadow — and explicitly never the primary fill, so
 * the actual letters stay sharp while the shadow softens, matching the CSS
 * preview's `text-shadow` blur radius (which is likewise a property of the
 * shadow layer, not the glyph fill). \blur has no independent "shadow-only"
 * mode in the ASS format — if an outline is also active it softens slightly
 * too, an inherent, well-known characteristic of this technique (used
 * throughout the ASS/karaoke-subtitling world for exactly this "soft shadow,
 * crisp text" look), not a bug. `getASSStyleFromConfig` already zeroes
 * `shadowSize` outside 'individual' mode, so this is naturally a no-op for
 * 'none'/'unified' — the Unified shadow gets its blur from ffmpeg's own
 * offscreen boxblur pass instead (see burnSubtitles), never from this tag.
 */
function buildShadowOverrideTag(options) {
  const { shadowColor, shadowOffsetX, shadowOffsetY, shadowSize } = options;
  let tag = '';

  if (shadowColor) {
    const clean = shadowColor.replace(/^&H/i, '').replace(/&$/, '').padStart(8, '0');
    const alpha = clean.substring(0, 2);
    const bgr = clean.substring(2, 8);
    tag += `\\4a&H${alpha}&\\4c&H${bgr}&`;
  }
  if (shadowOffsetX != null) tag += `\\xshad${shadowOffsetX}`;
  if (shadowOffsetY != null) tag += `\\yshad${shadowOffsetY}`;
  if (shadowSize > 0) tag += `\\blur${shadowSize}`;

  return tag ? `{${tag}}` : '';
}

/**
 * Builds the inline weight override tag for a keyword word: bold. Mirrors the
 * frontend preview's fontWeight rule exactly. Applied regardless of
 * active/inactive state, and regardless of animation mode.
 */
function toKeywordStyleTags(word, enableKeywordHighlighting) {
  if (!enableKeywordHighlighting || !word || !word.isKeyword) return '';
  return '\\b1';
}

/**
 * Builds one word's inline override block from resolveWordStyleMetadata's
 * generic metadata — the same function the CSS preview calls — so a
 * keyword-driven preset (e.g. WAYLES) never needs its own hardcoded ASS
 * tag logic. Font family/weight are emitted explicitly for every word
 * (not just keywords) so an override never leaks into the next word.
 *
 * @param {number} wordAlphaHex - Combined text/keyword opacity, as an ASS
 *   alpha byte, applied to this word's fill color (metadata.colorHex is
 *   plain hex and carries no alpha of its own).
 */
function buildKeywordDrivenWordBlock(word, wordText, metadata, baselineOutlineSize, baselineShadowSize, wordAlphaHex) {
  const rawAssColor = hexToASSColor(metadata.colorHex).replace(/^&H/i, '').replace(/&$/, '');
  const fillColorAss = `&H${wordAlphaHex}${rawAssColor.substring(2)}`;
  let openTag = toInlineColorTags(fillColorAss, 1);
  let closeTag = '';

  if (metadata.fontFamily) {
    // ASS's \fn tag takes a single literal font name — unlike CSS, it can't
    // take a comma-separated fallback list, so strip that down the same way
    // the base fontFamily is sanitized in getASSStyleFromConfig.
    const cleanFont = metadata.fontFamily.replace(/['"\r\n]/g, '').split(',')[0].trim();
    openTag += `\\fn${cleanFont}`;
  }
  const fontWeightNum = parseInt(metadata.fontWeight, 10) || 0;
  openTag += fontWeightNum >= 600 ? '\\b1' : '\\b0';
  openTag += metadata.italic ? '\\i1' : '\\i0';

  if (metadata.fontScale && metadata.fontScale !== 1) {
    const scalePct = Math.round(metadata.fontScale * 100);
    openTag += `\\fscx${scalePct}\\fscy${scalePct}`;
    closeTag += '\\fscx100\\fscy100';
  }

  if (metadata.shadow) {
    openTag += `\\shad${metadata.shadow.assDepth}`;
    closeTag += `\\shad${baselineShadowSize}`;
  }

  if (metadata.outline) {
    openTag += `\\bord${metadata.outline.assWidth}\\3c&H${hexToASSColor(metadata.outline.colorHex).replace(/^&H/i, '').substring(2)}&`;
    closeTag += `\\bord${baselineOutlineSize}`;
  }

  return `{${openTag}}${wordText}${closeTag ? `{${closeTag}}` : ''}`;
}

/**
 * Builds the Dialogue Text payload for one time-slice of a phrase: the full
 * phrase text is always present, only the active word's color (and, in pop
 * mode, scale) differs from the rest. An active keyword word gets a dedicated
 * keyword color instead of the normal active color; keyword bold/italic
 * styling applies regardless of active state.
 *
 * Keyword-driven presets (options.keywordDriven) instead derive every word's
 * complete appearance from resolveWordStyleMetadata (see
 * buildKeywordDrivenWordBlock) — the exact same metadata the CSS preview
 * uses — rather than the active/inactive/keyword-color logic below, which
 * legacy presets keep using unchanged.
 */
function buildStaticHighlightText(words, wordTexts, breakIndices, activeIdx, options) {
  const {
    animationMode, popScale, primaryColor, secondaryColor, enableKeywordHighlighting, keywordColor,
    keywordDriven, keywordStyleConfig, activeHighlightEnabled, outlineSize, shadowSize,
    primaryColorHex, secondaryColorHex, textOpacity, baseFontFamily, baseFontWeight
  } = options;
  let payload = buildShadowOverrideTag(options);

  wordTexts.forEach((wordText, idx) => {
    const isLineBreak = breakIndices.has(idx - 1);
    const isFirstWord = idx === 0;
    const prefixSpace = (isFirstWord || isLineBreak) ? '' : ' ';
    const lineBreakTag = isLineBreak ? '\\N' : '';
    const isActive = idx === activeIdx;
    const word = words[idx];

    if (keywordDriven) {
      const metadata = resolveWordStyleMetadata(word || {}, {
        keywordStyleConfig,
        keywordsEnabled: enableKeywordHighlighting,
        activeHighlightEnabled,
        isWordActive: isActive,
        mode: animationMode,
        activeHighlightColorHex: primaryColorHex,
        inactiveColorHex: secondaryColorHex,
        baseFontFamily,
        baseFontWeight
      });
      // Global text opacity always applies; a keyword word additionally
      // layers the dedicated "Keyword Opacity" slider on top, matching the
      // exact composition preview.js uses.
      const combinedOpacity = metadata.isKeyword
        ? (textOpacity ?? 100) * (keywordStyleConfig.opacity ?? 100) / 100
        : (textOpacity ?? 100);
      const wordAlphaHex = opacityToAssAlpha(combinedOpacity);
      payload += `${lineBreakTag}${prefixSpace}${buildKeywordDrivenWordBlock(word, wordText, metadata, outlineSize || 0, shadowSize || 0, wordAlphaHex)}`;
      return;
    }

    const isActiveKeyword = isActive && enableKeywordHighlighting && word?.isKeyword;

    let fillColor = isActive ? primaryColor : secondaryColor;
    if (isActiveKeyword) {
      fillColor = keywordColor;
    }

    const colorTags = toInlineColorTags(fillColor, 1);
    const styleTags = toKeywordStyleTags(word, enableKeywordHighlighting);
    const scaleOpenTag = (isActive && animationMode === 'pop') ? `\\fscx${popScale}\\fscy${popScale}` : '';
    const scaleCloseTag = (isActive && animationMode === 'pop') ? '{\\fscx100\\fscy100}' : '';

    payload += `${lineBreakTag}${prefixSpace}{${colorTags}${styleTags}${scaleOpenTag}}${wordText}${scaleCloseTag}`;
  });

  return payload;
}

/**
 * Word Mode: one Dialogue event per WORD, timed to that word's own Whisper
 * start/end (no new timing is generated or altered) — exactly one word
 * visible at a time, matching the preview's renderWordModeCaption exactly.
 * Reuses the same per-word tag builders the legacy/keyword-driven Sentence
 * mode paths already use (toInlineColorTags, toKeywordStyleTags,
 * buildKeywordDrivenWordBlock, resolveWordStyleMetadata) with the word
 * always treated as "active" (isWordActive: true) since it's the only one
 * on screen — there's no "inactive" word to contrast against. The shared
 * shadow/blur override block is emitted once per event exactly like every
 * other dialogue-generation path, so shadow color/offset/blur stay in sync.
 */
function generateWordModeDialogueEvents(phrase, options) {
  const {
    textCase, posOverrideTag, primaryColor, enableKeywordHighlighting, keywordColor,
    keywordDriven, keywordStyleConfig, keywordTextCase, activeHighlightEnabled, outlineSize, shadowSize,
    primaryColorHex, textOpacity, baseFontFamily, baseFontWeight
  } = options;

  const events = [];

  phrase.words.forEach((w) => {
    if (w.end - w.start < 0.001) return; // skip degenerate zero-length words

    const caseForWord = resolveWordTextCase(!!w.isKeyword, enableKeywordHighlighting, textCase, keywordTextCase);
    const wordText = applyCaseTransform((w.word || w.text || '').trim(), caseForWord, true);
    let payload = buildShadowOverrideTag(options);

    if (keywordDriven) {
      const metadata = resolveWordStyleMetadata(w, {
        keywordStyleConfig,
        keywordsEnabled: enableKeywordHighlighting,
        activeHighlightEnabled,
        isWordActive: true,
        mode: 'karaoke',
        activeHighlightColorHex: primaryColorHex,
        inactiveColorHex: primaryColorHex,
        baseFontFamily,
        baseFontWeight
      });
      const combinedOpacity = metadata.isKeyword
        ? (textOpacity ?? 100) * (keywordStyleConfig.opacity ?? 100) / 100
        : (textOpacity ?? 100);
      const wordAlphaHex = opacityToAssAlpha(combinedOpacity);
      payload += buildKeywordDrivenWordBlock(w, wordText, metadata, outlineSize || 0, shadowSize || 0, wordAlphaHex);
    } else {
      const isKeyword = enableKeywordHighlighting && w.isKeyword;
      const fillColor = isKeyword ? keywordColor : primaryColor;
      const colorTags = toInlineColorTags(fillColor, 1);
      const styleTags = toKeywordStyleTags(w, enableKeywordHighlighting);
      payload += `{${colorTags}${styleTags}}${wordText}`;
    }

    events.push(`Dialogue: 0,${formatASSTimestamp(w.start)},${formatASSTimestamp(w.end)},Default,,0,0,0,,${posOverrideTag || ''}${payload}`);
  });

  return events.join('\n');
}

/**
 * Builds one rolling-stack line's inline override block from
 * resolveWordStyleMetadata's generic metadata, reusing buildKeywordDrivenWordBlock
 * verbatim (it only ever reads wordText/metadata, never the raw word object,
 * so a whole joined chunk line is a drop-in "word" as far as it's concerned).
 * isWordActive is passed in by the caller: true for the bottom/active chunk,
 * false for the top/previous chunk — this is what naturally limits the pop
 * scale-up and the "active" highlight color to the bottom line only, via the
 * exact same resolveWordStyleMetadata logic every other mode already uses.
 */
function buildRollingStackLineBlock(chunk, options, isWordActive) {
  const {
    textCase, enableKeywordHighlighting, keywordStyleConfig, keywordTextCase, activeHighlightEnabled,
    animationMode, primaryColorHex, secondaryColorHex, baseFontFamily, baseFontWeight,
    outlineSize, shadowSize, textOpacity
  } = options;

  const caseForChunk = resolveWordTextCase(chunk.type === 'keyword', enableKeywordHighlighting, textCase, keywordTextCase);
  const lineText = applyCaseTransform(chunkRawText(chunk), caseForChunk, true);

  const metadata = resolveWordStyleMetadata({ isKeyword: chunk.type === 'keyword' }, {
    keywordStyleConfig,
    keywordsEnabled: enableKeywordHighlighting,
    activeHighlightEnabled,
    isWordActive,
    mode: animationMode,
    activeHighlightColorHex: primaryColorHex,
    inactiveColorHex: secondaryColorHex,
    baseFontFamily,
    baseFontWeight
  });

  const combinedOpacity = metadata.isKeyword
    ? (textOpacity ?? 100) * (keywordStyleConfig.opacity ?? 100) / 100
    : (textOpacity ?? 100);
  const wordAlphaHex = opacityToAssAlpha(combinedOpacity);

  return buildKeywordDrivenWordBlock(null, lineText, metadata, outlineSize || 0, shadowSize || 0, wordAlphaHex);
}

/**
 * Rolling Stack: a two-layer caption layout built around detected keywords
 * (see shared/rollingStack.js for the shared chunking/slicing logic both
 * this and the CSS preview call). One Dialogue event per rolling-stack
 * slice, and slices only exist where at least one chunk is genuinely active
 * — buildRollingStackSlices already drops gaps entirely, so a chunk can
 * never render past its own end timestamp just because nothing new has
 * started yet. Most slices have only a `bottom` chunk (single line); a slice
 * gets a `top` chunk too only when two chunks' own timestamps genuinely
 * overlap, in which case the text is the top chunk's line, an ASS `\N` line
 * break, then the bottom chunk's line — under the Style's existing
 * bottom-center alignment this stacks them with no manual pixel positioning
 * needed.
 */
function generateRollingStackDialogueEvents(phrase, options) {
  const { posOverrideTag } = options;
  const slices = buildRollingStackSlices(phrase);

  return slices.map((slice) => {
    let payload = buildShadowOverrideTag(options);
    if (slice.top) {
      payload += buildRollingStackLineBlock(slice.top, options, false);
      payload += '\\N';
    }
    payload += buildRollingStackLineBlock(slice.bottom, options, true);
    return `Dialogue: 0,${formatASSTimestamp(slice.start)},${formatASSTimestamp(slice.end)},Default,,0,0,0,,${posOverrideTag || ''}${payload}`;
  }).join('\n');
}

/**
 * Generates one Dialogue event per word-boundary time-slice within a phrase.
 * The full phrase is always visible; only the currently active word's color
 * (and scale, for 'pop') differs — no word is ever hidden or swept/revealed.
 * This mirrors the preview's per-frame word coloring exactly (word is active
 * iff currentTime falls within its own [start, end]).
 *
 * Used for 'karaoke', 'instant', and 'pop' modes, which are all the same
 * hard-swap highlight behavior in the preview; only the scale tag differs.
 */
function generateStaticHighlightDialogueEvents(phrase, options) {
  const { textCase, posOverrideTag, enableKeywordHighlighting, keywordTextCase } = options;
  const breakIndices = new Set(phrase.breakAfterIndices || []);

  const wordTexts = phrase.words.map((w, idx) => {
    const raw = (w.word || w.text || '').trim();
    const caseForWord = resolveWordTextCase(!!w.isKeyword, enableKeywordHighlighting, textCase, keywordTextCase);
    return applyCaseTransform(raw, caseForWord, idx === 0);
  });

  const clamp = (t) => Math.max(phrase.start, Math.min(phrase.end, t));
  const boundarySet = new Set([phrase.start, phrase.end]);
  phrase.words.forEach((w) => {
    boundarySet.add(clamp(w.start));
    boundarySet.add(clamp(w.end));
  });
  const boundaries = Array.from(boundarySet).sort((a, b) => a - b);

  const events = [];
  for (let i = 0; i < boundaries.length - 1; i++) {
    const sliceStart = boundaries[i];
    const sliceEnd = boundaries[i + 1];
    if (sliceEnd - sliceStart < 0.001) continue; // skip degenerate zero-length slices

    const activeIdx = phrase.words.findIndex((w) => sliceStart >= w.start - 0.001 && sliceStart < w.end - 0.001);
    const text = buildStaticHighlightText(phrase.words, wordTexts, breakIndices, activeIdx, options);
    events.push(`Dialogue: 0,${formatASSTimestamp(sliceStart)},${formatASSTimestamp(sliceEnd)},Default,,0,0,0,,${posOverrideTag || ''}${text}`);
  }

  return events.join('\n');
}

/**
 * Generates a single karaoke-tagged Dialogue event where future words remain
 * hidden until spoken. Distinct from the other modes by design: this is the
 * only mode where words are deliberately revealed/hidden over time.
 */
function generateTypewriterDialogueLine(phrase, options) {
  const { textCase, posOverrideTag, enableKeywordHighlighting, keywordTextCase } = options;
  const breakIndices = new Set(phrase.breakAfterIndices || []);

  const startStr = formatASSTimestamp(phrase.start);
  const endStr = formatASSTimestamp(phrase.end);

  let textPayload = buildShadowOverrideTag(options);
  let lastTime = phrase.start;

  phrase.words.forEach((w, idx) => {
    const delay = Math.max(0, Math.round((w.start - lastTime) * 100));
    const duration = Math.max(1, Math.round((w.end - w.start) * 100));

    const caseForWord = resolveWordTextCase(!!w.isKeyword, enableKeywordHighlighting, textCase, keywordTextCase);
    const wordText = applyCaseTransform((w.word || w.text || '').trim(), caseForWord, idx === 0);

    const isFirstWord = idx === 0;
    const isLineBreak = breakIndices.has(idx - 1);
    const prefixSpace = (isFirstWord || isLineBreak) ? '' : ' ';
    const lineBreakTag = isLineBreak ? '\\N' : '';
    // Typewriter has no existing active/inactive color swap in ASS, so keywords
    // only get bold/italic styling here (no dedicated keyword color), keeping
    // this mode self-consistent with its own current rendering model.
    const styleTags = toKeywordStyleTags(w, enableKeywordHighlighting);

    if (delay > 0) {
      textPayload += `${lineBreakTag}{\\alpha&HFF&\\k${delay}}`;
    }
    textPayload += `${prefixSpace}{\\alpha&H00&\\kf${duration}${styleTags}}${wordText}`;

    lastTime = w.end;
  });

  return `Dialogue: 0,${startStr},${endStr},Default,,0,0,0,,${posOverrideTag || ''}${textPayload}`;
}

/**
 * Converts a phrase object containing word units into ASS Dialogue event(s),
 * matching the preview's word-highlighting behavior exactly for the given
 * animation mode.
 * Supports:
 *  - 'karaoke'/'instant': Full phrase always visible; only the current word
 *    shows the active color, everything else shows the inactive color.
 *  - 'pop': Same hard-swap coloring as karaoke, plus the active word scales up.
 *  - 'typewriter': Future words hidden until spoken (intentionally distinct).
 *
 * @param {object} phrase - Unified phrase containing start, end, text, words array, and breakAfterIndices.
 * @param {object|string} options - Style options or textCase string.
 * @returns {string} One or more newline-joined ASS Dialogue Event lines.
 */
export function generateASSDialogueLine(phrase, options = {}) {
  const textCase = typeof options === 'string' ? options : (options.textCase || 'uppercase');
  const animationMode = typeof options === 'object' && options.animationMode ? options.animationMode : 'karaoke';
  const popScale = typeof options === 'object' && options.popScale ? Math.round(options.popScale) : 118;
  const primaryColor = (typeof options === 'object' && options.primaryColor) || DEFAULT_PRIMARY_COLOR;
  const secondaryColor = (typeof options === 'object' && options.secondaryColor) || DEFAULT_SECONDARY_COLOR;
  const posOverrideTag = (typeof options === 'object' && options.posOverrideTag) || null;
  const enableKeywordHighlighting = typeof options === 'object' && options.enableKeywordHighlighting !== false;
  const keywordColor = (typeof options === 'object' && options.keywordColor) || DEFAULT_PRIMARY_COLOR;
  const shadowColor = (typeof options === 'object' && options.shadowColor) || null;
  const shadowOffsetX = (typeof options === 'object' && options.shadowOffsetX != null) ? options.shadowOffsetX : null;
  const shadowOffsetY = (typeof options === 'object' && options.shadowOffsetY != null) ? options.shadowOffsetY : null;

  // Keyword-driven preset support (e.g. WAYLES) — all optional/undefined for
  // legacy presets, which never set keywordDriven and so never touch this path.
  const primaryColorHex = (typeof options === 'object' && options.primaryColorHex) || null;
  const secondaryColorHex = (typeof options === 'object' && options.secondaryColorHex) || null;
  const keywordDriven = typeof options === 'object' && !!options.keywordDriven;
  const keywordStyleConfig = (typeof options === 'object' && options.keywordStyleConfig) || null;
  const keywordTextCase = (typeof options === 'object' && options.keywordTextCase) || null;
  const activeHighlightEnabled = typeof options === 'object' ? options.activeHighlightEnabled !== false : true;
  const outlineSize = (typeof options === 'object' && options.outlineSize) || 0;
  const shadowSize = (typeof options === 'object' && options.shadowSize) || 0;
  const textOpacity = (typeof options === 'object' && options.textOpacity != null) ? options.textOpacity : 100;
  const baseFontFamily = (typeof options === 'object' && options.baseFontFamily) || null;
  const baseFontWeight = (typeof options === 'object' && options.baseFontWeight) || null;
  const captionMode = typeof options === 'object' && (options.captionMode === 'word' || options.captionMode === 'rolling-stack')
    ? options.captionMode
    : 'sentence';

  const resolvedOptions = {
    textCase, animationMode, popScale, primaryColor, secondaryColor,
    posOverrideTag, enableKeywordHighlighting, keywordColor,
    shadowColor, shadowOffsetX, shadowOffsetY,
    primaryColorHex, secondaryColorHex, keywordDriven, keywordStyleConfig, keywordTextCase,
    activeHighlightEnabled, outlineSize, shadowSize, textOpacity,
    baseFontFamily, baseFontWeight
  };

  // Word Mode and Rolling Stack both override every animation mode: they're
  // distinct rendering shapes from all of karaoke/pop/instant/typewriter's
  // "full phrase, differing emphasis" model, so they're checked first
  // regardless of animationMode (see generateWordModeDialogueEvents /
  // generateRollingStackDialogueEvents).
  if (captionMode === 'word') {
    return generateWordModeDialogueEvents(phrase, resolvedOptions);
  }

  if (captionMode === 'rolling-stack') {
    return generateRollingStackDialogueEvents(phrase, resolvedOptions);
  }

  if (animationMode === 'typewriter') {
    return generateTypewriterDialogueLine(phrase, resolvedOptions);
  }

  return generateStaticHighlightDialogueEvents(phrase, resolvedOptions);
}


/**
 * Helper to translate frontend styles choices into raw ASS style configurations.
 * Delegated to the shared single source of truth captionConfig schema.
 *
 * @param {object} params - Input style settings from the client.
 * @returns {object} The resolved ASS Style parameters.
 */
export function resolveASSStyle(params = {}) {
  return getASSStyleFromConfig(params);
}

/**
 * Builds the ASS header for the Unified Shadow's own silhouette track: a
 * single flat-colored style with NO outline/native shadow of its own. The
 * blur and offset that make it look like a shadow are applied afterward by
 * ffmpeg to this track's rasterized output as a whole (see burnSubtitles'
 * unifiedShadow filter graph) — not per-glyph by libass — which is what lets
 * it merge into one continuous silhouette instead of a shadow behind every
 * individual character.
 *
 * @param {object} resolvedStyle - Output of getASSStyleFromConfig.
 */
